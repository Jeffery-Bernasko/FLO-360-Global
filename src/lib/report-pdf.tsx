import {
  Document,
  Page,
  StyleSheet,
  Text,
  View,
  renderToBuffer,
} from "@react-pdf/renderer";
import type { ReactNode } from "react";
import { formatGhs } from "@/lib/money";
import { rangeLabel } from "@/lib/report-csv";
import {
  type DateRange,
  type PerCustomerRow,
  type PerSupplierRow,
  type StockMovementRow,
} from "@/lib/reports";

const styles = StyleSheet.create({
  page: {
    padding: 32,
    fontSize: 9,
    fontFamily: "Helvetica",
    color: "#0f172a",
  },
  header: {
    flexDirection: "row",
    justifyContent: "space-between",
    marginBottom: 18,
  },
  title: { fontSize: 18, fontWeight: 700 },
  subtitle: { marginTop: 4, color: "#64748b" },
  meta: { textAlign: "right", color: "#64748b" },
  table: { borderTopWidth: 1, borderTopColor: "#cbd5e1" },
  row: {
    flexDirection: "row",
    borderBottomWidth: 1,
    borderBottomColor: "#e2e8f0",
    paddingVertical: 6,
  },
  head: { backgroundColor: "#f8fafc", fontWeight: 700 },
  grow: { flexGrow: 1, paddingRight: 6 },
  small: { width: 58, paddingRight: 6 },
  medium: { width: 76, paddingRight: 6 },
  right: { textAlign: "right" },
  footer: {
    position: "absolute",
    bottom: 20,
    left: 32,
    right: 32,
    color: "#94a3b8",
    fontSize: 8,
    flexDirection: "row",
    justifyContent: "space-between",
  },
});

type ReportShellProps = {
  title: string;
  range: DateRange;
  generatedBy: string;
  children: ReactNode;
};

function ReportShell({ title, range, generatedBy, children }: ReportShellProps) {
  return (
    <Document title={title}>
      <Page size="A4" style={styles.page}>
        <View style={styles.header}>
          <View>
            <Text style={styles.title}>FLO 360 Global</Text>
            <Text style={styles.subtitle}>{title}</Text>
          </View>
          <View style={styles.meta}>
            <Text>{rangeLabel(range)}</Text>
            <Text>Generated by {generatedBy}</Text>
          </View>
        </View>
        {children}
        <View style={styles.footer} fixed>
          <Text>Generated {new Date().toISOString()}</Text>
          <Text
            render={({ pageNumber, totalPages }) =>
              `Page ${pageNumber} of ${totalPages}`
            }
          />
        </View>
      </Page>
    </Document>
  );
}

export async function renderStockMovementReportPdf({
  rows,
  range,
  generatedBy,
}: {
  rows: StockMovementRow[];
  range: DateRange;
  generatedBy: string;
}): Promise<Buffer> {
  return renderToBuffer(
    <ReportShell title="Stock Movement Report" range={range} generatedBy={generatedBy}>
      <View style={styles.table}>
        <View style={[styles.row, styles.head]}>
          <Text style={styles.medium}>Date</Text>
          <Text style={styles.small}>Kind</Text>
          <Text style={styles.grow}>Party / reason</Text>
          <Text style={[styles.small, styles.right]}>Boxes</Text>
          <Text style={[styles.medium, styles.right]}>Balance</Text>
        </View>
        {rows.map((row) => (
          <View key={row.id} style={styles.row}>
            <Text style={styles.medium}>
              {row.createdAt.toISOString().slice(0, 10)}
            </Text>
            <Text style={styles.small}>{row.kind}</Text>
            <Text style={styles.grow}>{row.partyName ?? row.reason ?? "-"}</Text>
            <Text style={[styles.small, styles.right]}>{row.boxesDelta}</Text>
            <Text style={[styles.medium, styles.right]}>{row.runningBalance}</Text>
          </View>
        ))}
      </View>
    </ReportShell>,
  );
}

export async function renderCustomerReportPdf({
  rows,
  range,
  generatedBy,
}: {
  rows: PerCustomerRow[];
  range: DateRange;
  generatedBy: string;
}): Promise<Buffer> {
  return renderToBuffer(
    <ReportShell title="Per-Customer Report" range={range} generatedBy={generatedBy}>
      <View style={styles.table}>
        <View style={[styles.row, styles.head]}>
          <Text style={styles.grow}>Customer</Text>
          <Text style={[styles.small, styles.right]}>Boxes</Text>
          <Text style={[styles.medium, styles.right]}>Total</Text>
          <Text style={[styles.small, styles.right]}>Dispatches</Text>
        </View>
        {rows.map((row) => (
          <View key={row.customerId} style={styles.row}>
            <Text style={styles.grow}>{row.customerName}</Text>
            <Text style={[styles.small, styles.right]}>{row.totalBoxes}</Text>
            <Text style={[styles.medium, styles.right]}>{formatGhs(row.totalPesewas)}</Text>
            <Text style={[styles.small, styles.right]}>{row.dispatchCount}</Text>
          </View>
        ))}
      </View>
    </ReportShell>,
  );
}

